
USE DATABASE MOVIES_DB;
USE SCHEMA GOLD;


CREATE TABLE IF NOT EXISTS GENRE_ANALYTICS (
    GENRE VARCHAR,
    TOTAL_MOVIES INTEGER,
    AVERAGE_SCORE FLOAT,
    TOTAL_GROSS FLOAT
);


CREATE OR REPLACE STAGE MOVIES_GOLD_STAGE
    URL = 's3://sagar-movies-data-project/gold/'
    STORAGE_INTEGRATION = MOVIES_S3_INTEGRATION;


TRUNCATE TABLE GENRE_ANALYTICS;

COPY INTO GENRE_ANALYTICS
FROM @MOVIES_GOLD_STAGE
FILE_FORMAT = (
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
)
PATTERN = '.*genre_analytics\.csv'
FORCE = TRUE
ON_ERROR = 'CONTINUE';

SELECT *
FROM GENRE_ANALYTICS
ORDER BY GENRE;